#!/usr/bin/env python3
"""
ln_studio_skill/tools/generate_ln_library.py
Infor LN Studio Library & Extension Generator.

Generates production-grade .lib XML files matching Infor LN Studio 10.8 specifications:
- General DLLs in <pkg>/library/<mod>/
- Session Extensions (ess) in <pkg>/library/ess/ (sourceType=8)
- Table Extensions (est) in <pkg>/library/est/ (sourceType=6)
Seeded with official #context_on / #context_off hook blocks and enforcing Read-Only guardrails.
"""

import os
import sys
import argparse
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, List, Optional, Union

_SKILL_ROOT = Path(__file__).resolve().parent.parent
_TOOLS_DIR = Path(__file__).resolve().parent
if str(_TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(_TOOLS_DIR))

from ln_schema_parser import parse_schema_file
from generate_ln_table import get_current_iso_time
from ln_workspace_manager import resolve_activity, detect_current_activity
from scm_guardrails import assert_file_writable, ReadOnlyComponentError


def generate_library_xml(
    lib_spec: Dict[str, Any],
    application: str,
    script_override: Optional[str] = None
) -> str:
    """Generates standard <DR_Module> .lib XML for DLL, ess, or est."""
    code = lib_spec["code"]
    desc = lib_spec.get("description", code)
    l_type = lib_spec.get("type", "dll").lower()
    target = lib_spec.get("target", "")
    ver = lib_spec.get("version_id", "B61O_a_ext")
    now_iso = get_current_iso_time()

    source_type = "8" if l_type == "session_extension" else "6"

    # Default starter script with official template structures
    if script_override:
        script_code = script_override
    elif l_type == "session_extension":
        script_code = (
            f"|*******************************************************************************\n"
            f"|* Session Extension: {code} ({target})\n"
            f"|* {desc}\n"
            f"|*******************************************************************************\n\n"
            f"function extern boolean function.option.sample.is.enabled()\n"
            f"{{\n"
            f"\treturn(true)\n"
            f"}}\n\n"
            f"function extern void function.option.sample.after.command()\n"
            f"{{\n"
            f"\t|* Implementation logic\n"
            f"}}\n"
        )
    elif l_type == "table_extension":
        script_code = (
            f"|*******************************************************************************\n"
            f"|* {code}   0  VRC {ver}\n"
            f"|* Extension Script for Table {target}\n"
            f"|*******************************************************************************\n"
            f"|* Script Type: Library\n"
            f"|* WARNING: Do NOT edit this file using the Baan Tools (SCM) !!!\n"
            f"|*******************************************************************************\n\n"
            f"| Hook declarations\n"
            f'#context_on "declarations"\n'
            f"|global declarations for extension script.\n"
            f"#context_off\n\n"
            f"| Additional generated declarations\n"
            f"table\tt{target}\n"
            f"#include <bic_dal2>\n"
            f"#include <bic_tableext>\n\n"
            f"| Hook functions\n"
            f'#context_on "functions"\n'
            f"|common functions to be used in extension script.\n"
            f"#context_off\n\n"
            f"| Hook method.is.allowed\n"
            f'#context_on "method.is.allowed"\n'
            f"function extern boolean method.is.allowed(long method)\n"
            f"{{\n"
            f"\ton case method\n"
            f"\tcase DAL_NEW:\n"
            f"\t\tbreak\n"
            f"\tcase DAL_UPDATE:\n"
            f"\t\tbreak\n"
            f"\tcase DAL_DESTROY:\n"
            f"\t\tbreak\n"
            f"\tendcase\n"
            f"\treturn(true)\n"
            f"}}\n"
            f"#context_off\n\n"
            f"| Hook before.save\n"
            f'#context_on "before.save"\n'
            f"function extern long before.save.object(long mode)\n"
            f"{{\n"
            f"\treturn (0)\n"
            f"}}\n"
            f"#context_off\n\n"
            f"| Hook after.save\n"
            f'#context_on "after.save"\n'
            f"function extern long after.save.object(long mode)\n"
            f"{{\n"
            f"\treturn (0)\n"
            f"}}\n"
            f"#context_off\n\n"
            f"function extern long get.extension.point.version()\n"
            f"{{\n"
            f"\treturn(3)\n"
            f"}}\n"
        )
    else:  # General DLL
        script_code = (
            f"|*******************************************************************************\n"
            f"|* {code}   0  VRC {ver}\n"
            f"|* {desc}\n"
            f"|*******************************************************************************\n"
            f"|* Script Type: Library\n"
            f"|*******************************************************************************\n\n"
            f"#include <bic_dam>\n\n"
            f"function extern long sample.function()\n"
            f"{{\n"
            f"\treturn(0)\n"
            f"}}\n"
        )

    escaped_script = (
        script_code.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )

    attachments_xml = f'<Attachment><type>techdoc</type><name>{code}</name></Attachment>'
    if l_type != "session_extension":
        attachments_xml = f'<Attachment><type>relnotes</type><name>{code}</name></Attachment>' + attachments_xml

    extra_constraints = "<additionalConstraints>2610</additionalConstraints><additionalInstructions/><keyword>||</keyword>" if l_type != "session_extension" else ""

    xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="no"?>'
        f'<DR_Module>'
        f'<description>{desc}</description>'
        f'<versionID>{ver}</versionID>'
        f'<type>library</type>'
        f'<name>{code}</name>'
        f'<Version>'
        f'<ObjectID/><classID/><checkInLabel/><documentation/>'
        f'<isExpired>no</isExpired>'
        f'<isCheckedOutParallel>no</isCheckedOutParallel>'
        f'<isCheckedOut>no</isCheckedOut>'
        f'<modificationDateTime>{now_iso}</modificationDateTime>'
        f'<modifiedBy>agent</modifiedBy>'
        f'<creationDateTime>{now_iso}</creationDateTime>'
        f'<createdBy>agent</createdBy>'
        f'</Version>'
        f'<Source>'
        f'<sourceVersion>'
        f'<ObjectID/><classID/><checkInLabel/><documentation/>'
        f'<isExpired>no</isExpired>'
        f'<isCheckedOutParallel>no</isCheckedOutParallel>'
        f'<isCheckedOut>no</isCheckedOut>'
        f'<modificationDateTime>{now_iso}</modificationDateTime>'
        f'<modifiedBy>agent</modifiedBy>'
        f'<creationDateTime>{now_iso}</creationDateTime>'
        f'<createdBy>agent</createdBy>'
        f'</sourceVersion>'
        f'<sourceVersionID>{ver}</sourceVersionID>'
        f'<sourceObjectID>1</sourceObjectID>'
        f'<expression>{escaped_script}</expression>'
        f'<expressionLanguageType>Baan4C</expressionLanguageType>'
        f'<sourceType>{source_type}</sourceType>'
        f'<sourceDescription>{desc}</sourceDescription>'
        f'<sourceName>{code}</sourceName>'
        f'</Source>'
        f'<documentation/>'
        f'{attachments_xml}'
        f'{extra_constraints}'
        f'<application>{application}</application>'
        f'</DR_Module>'
    )
    return xml


def generate_libraries(
    schema_file: Union[str, Path, Dict[str, Any]],
    library_code: Optional[str] = None,
    activity_name: Optional[str] = None,
    output_dir: Optional[str] = None,
    workspace_name: Optional[str] = None,
    activity_path: Optional[str] = None,
    dry_run: bool = False
) -> List[Dict[str, str]]:
    """
    Generates .lib XML files for declared libraries in schema.
    """
    if isinstance(schema_file, dict):
        schema = schema_file
    else:
        schema = parse_schema_file(schema_file)

    ver = schema.get("version_id", "B61O_a_ext")
    app_code = schema.get("application", "")

    # Target directory resolution
    target_root: Path
    if output_dir:
        target_root = Path(output_dir).resolve()
        if not app_code:
            app_code = "EXTce01105"
    elif activity_path or activity_name:
        resolved = resolve_activity(activity_name, workspace_name=workspace_name, activity_path=activity_path)
        if not resolved:
            raise ValueError(f"Could not resolve activity: '{activity_path or activity_name}'")
        target_root = Path(resolved["path"])
        if not app_code:
            app_code = resolved["project"]
    else:
        detected = detect_current_activity()
        if detected:
            target_root = Path(detected["path"])
            if not app_code:
                app_code = detected["project"]
        elif dry_run:
            target_root = Path.cwd() / "output"
            if not app_code:
                app_code = "EXTce01105"
        else:
            raise ValueError("Explicit --activity, --activity-path, or --output-dir required to generate libraries.")

    libs_to_gen = schema.get("libraries", [])
    if library_code:
        libs_to_gen = [l for l in libs_to_gen if l["code"].lower() == library_code.lower()]
        if not libs_to_gen:
            raise ValueError(f"Library '{library_code}' not found in schema.")

    generated = []
    for lib in libs_to_gen:
        code = lib["code"]
        pkg = code[:2]
        l_type = lib.get("type", "dll").lower()

        # Destination subdirectory
        if l_type == "session_extension":
            lib_dir = target_root / pkg / "library" / "ess"
        elif l_type == "table_extension":
            lib_dir = target_root / pkg / "library" / "est"
        else:
            mod = lib.get("module", code[2:5] if len(code) >= 5 else "gen")
            lib_dir = target_root / pkg / "library" / mod

        lib_path = lib_dir / f"{code}.lib"
        xml_content = generate_library_xml(lib, application=app_code)
        generated.append({
            "type": "library",
            "name": code,
            "path": str(lib_path),
            "content": xml_content
        })

    if not dry_run:
        for item in generated:
            p = Path(item["path"])
            assert_file_writable(p, target_root)

        for item in generated:
            p = Path(item["path"])
            p.parent.mkdir(parents=True, exist_ok=True)
            with open(p, "w", encoding="utf-8") as f:
                f.write(item["content"])

    return generated


def main():
    parser = argparse.ArgumentParser(description="Generate Infor LN Library XML (.lib) from Schema")
    parser.add_argument("--spec", required=True, help="Path to schema YAML/JSON file")
    parser.add_argument("--code", help="Specific library code to generate")
    parser.add_argument("--activity", help="Target activity folder name or activity code")
    parser.add_argument("--activity-path", help="Direct activity directory path")
    parser.add_argument("--workspace", help="Filter by workspace name")
    parser.add_argument("--output-dir", help="Direct target directory path (overrides activity)")
    parser.add_argument("--dry-run", action="store_true", help="Print plan without writing files to disk")

    args = parser.parse_args()

    try:
        files = generate_libraries(
            schema_file=args.spec,
            library_code=args.code,
            activity_name=args.activity,
            activity_path=args.activity_path,
            workspace_name=args.workspace,
            output_dir=args.output_dir,
            dry_run=args.dry_run
        )
        mode_str = "[DRY-RUN] Would generate" if args.dry_run else "[SUCCESS] Generated"
        print(f"{mode_str} {len(files)} library file(s):")
        for f in files:
            print(f"  ({f['type'].upper():<7}) {f['name']:<20} -> {f['path']}")
    except ReadOnlyComponentError as e:
        print(str(e), file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"[ERROR] Library generation failed: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
